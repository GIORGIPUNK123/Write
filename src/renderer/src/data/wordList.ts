export const getRandomWords = (amount: number): string[] => {
  const result: string[] = [];
  const pool = [...WORD_LIST];

  for (let i = 0; i < amount; i++) {
    if (pool.length === 0) {
      pool.push(...WORD_LIST);
    }
    const index = Math.floor(Math.random() * pool.length);
    result.push(pool.splice(index, 1)[0].toLowerCase());
  }

  return result;
};
